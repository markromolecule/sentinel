import PDFDocument from 'pdfkit';
import { PDF_LAYOUT } from './pdf-page-layout';
import {
    ExamResultsReportViewModel,
    mapSourceToViewModel,
} from './exam-results-report-view-model';
import { renderPdfDocumentBuffer } from './render-pdf-buffer';
import { HeaderConfig } from './pdf-header-renderer';
import { FooterConfig } from './pdf-footer-renderer';
import type { ExamReportExportSource } from '../data/exam-reports/get-exam-report-export-source';

/**
 * Draws a section header with accent line and text.
 */
function drawSectionHeader(doc: typeof PDFDocument, title: string, y: number): number {
    doc.save();
    doc.fillColor(PDF_LAYOUT.colors.sentinelPrimary).rect(PDF_LAYOUT.marginLeft, y, 4, 15).fill();

    doc.fillColor(PDF_LAYOUT.colors.textPrimary)
        .font(PDF_LAYOUT.fonts.bold)
        .fontSize(11)
        .text(title, PDF_LAYOUT.marginLeft + 10, y + 2);

    doc.restore();
    return y + 25;
}

/**
 * Checks if a section requires a page break.
 */
function checkPageBreak(doc: typeof PDFDocument, currentY: number, heightNeeded: number): number {
    if (currentY + heightNeeded > PDF_LAYOUT.pageHeight - PDF_LAYOUT.marginBottom) {
        doc.addPage();
        return PDF_LAYOUT.marginTop;
    }
    return currentY;
}

const studentCols = [
    { name: 'Student Name / No.', width: 140, align: 'left' },
    { name: 'Section', width: 80, align: 'left' },
    { name: 'Status', width: 75, align: 'center' },
    { name: 'Score', width: 50, align: 'right' },
    { name: 'Attempt', width: 52, align: 'center' },
    { name: 'Incidents (P/R/C/D)', width: 90, align: 'right' },
] as const;

/**
 * Draws the table header for the student attempts listing.
 */
function drawStudentTableHeader(doc: typeof PDFDocument, y: number): number {
    doc.save();
    doc.rect(
        PDF_LAYOUT.marginLeft,
        y,
        PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight,
        20,
    )
        .fillColor('#374151') // dark gray
        .fill();

    let curX = PDF_LAYOUT.marginLeft;
    doc.fillColor('#FFFFFF').font(PDF_LAYOUT.fonts.bold).fontSize(8);

    studentCols.forEach((col) => {
        const align = col.align;
        const padding = align === 'left' ? 6 : align === 'right' ? -6 : 0;
        doc.text(col.name, curX + padding, y + 6, {
            width: col.width,
            align,
        });
        curX += col.width;
    });
    doc.restore();
    return y + 20;
}

/**
 * Draws the body content of the Examination Results Report PDF.
 */
export function drawExamResultsReportBody(
    doc: typeof PDFDocument,
    data: ExamResultsReportViewModel,
): void {
    let y = PDF_LAYOUT.marginTop;

    // 1. Cover / Metadata Card
    doc.save();
    doc.rect(
        PDF_LAYOUT.marginLeft,
        y,
        PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight,
        75,
    )
        .fillColor('#F9FAFB')
        .fill();
    doc.rect(
        PDF_LAYOUT.marginLeft,
        y,
        PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight,
        75,
    )
        .strokeColor(PDF_LAYOUT.colors.border)
        .lineWidth(0.5)
        .stroke();

    doc.fillColor(PDF_LAYOUT.colors.textPrimary)
        .font(PDF_LAYOUT.fonts.bold)
        .fontSize(12)
        .text(data.examTitle, PDF_LAYOUT.marginLeft + 12, y + 10);

    doc.fillColor(PDF_LAYOUT.colors.textSecondary).font(PDF_LAYOUT.fonts.regular).fontSize(8);

    doc.text(`Subject: ${data.subjectCode} - ${data.subjectName}`, PDF_LAYOUT.marginLeft + 12, y + 28);
    const options: Intl.DateTimeFormatOptions = {
        timeZone: 'Asia/Manila',
        year: 'numeric',
        month: 'numeric',
        day: 'numeric',
        hour: 'numeric',
        minute: 'numeric',
        second: 'numeric',
    };
    const schedDateStr = new Date(data.scheduledDate).toLocaleString('en-US', options);
    const endDateStr = new Date(data.endDateTime).toLocaleString('en-US', options);

    doc.text(`Scheduled: ${schedDateStr} (PHT) to ${endDateStr} (PHT)`, PDF_LAYOUT.marginLeft + 12, y + 40);
    doc.text(`Duration: ${data.durationMinutes} mins   |   Passing Score: ${data.passingScore}%`, PDF_LAYOUT.marginLeft + 12, y + 52);

    const generatedDateStr = new Date(data.generatedAt).toLocaleString('en-US', options);
    doc.text(
        `Generated By: ${data.generatedBy}`,
        PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginRight - 220,
        y + 28,
        { width: 200, align: 'right' },
    );
    doc.text(
        `Generated At: ${generatedDateStr} (PHT)`,
        PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginRight - 220,
        y + 40,
        { width: 200, align: 'right' },
    );
    doc.text(
        `Institution: ${data.institutionName}`,
        PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginRight - 220,
        y + 52,
        { width: 200, align: 'right' },
    );
    doc.restore();
    y += 90;

    // 2. Summary KPI Grid
    y = drawSectionHeader(doc, 'EXAMINATION METRICS SUMMARY', y);

    const cardWidth =
        (PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight - 20) / 3;
    const cardHeight = 45;

    const kpis = [
        { label: 'Total Assigned', value: data.summary.totalStudents.toString(), color: '#3B82F6' },
        { label: 'Completions', value: data.summary.totalCompletions.toString(), color: '#10B981' },
        { label: 'Pass Rate', value: `${data.summary.passRate}%`, color: '#6366F1' },
        { label: 'Average Score', value: `${data.summary.averageScore}%`, color: '#F59E0B' },
        { label: 'Absent Students', value: data.summary.totalAbsent.toString(), color: '#EC4899' },
        { label: 'Integrity Flags', value: data.summary.totalIncidents.toString(), color: '#EF4444' },
    ];

    doc.save();
    kpis.forEach((kpi, idx) => {
        const row = Math.floor(idx / 3);
        const col = idx % 3;
        const cardX = PDF_LAYOUT.marginLeft + col * (cardWidth + 10);
        const cardY = y + row * (cardHeight + 10);

        doc.rect(cardX, cardY, cardWidth, cardHeight).fillColor('#F3F4F6').fill();
        doc.rect(cardX, cardY, 4, cardHeight).fillColor(kpi.color).fill();

        doc.fillColor(PDF_LAYOUT.colors.textPrimary)
            .font(PDF_LAYOUT.fonts.bold)
            .fontSize(14)
            .text(kpi.value, cardX + 10, cardY + 8);

        doc.fillColor(PDF_LAYOUT.colors.textSecondary)
            .font(PDF_LAYOUT.fonts.regular)
            .fontSize(7.5)
            .text(kpi.label, cardX + 10, cardY + 26);
    });
    doc.restore();
    y += 115;

    // 3. Student Results Table
    y = checkPageBreak(doc, y, 60);
    y = drawSectionHeader(doc, 'STUDENT PERFORMANCE & INTEGRITY LISTING', y);

    y = drawStudentTableHeader(doc, y);

    doc.save();
    doc.font(PDF_LAYOUT.fonts.regular).fontSize(8);

    if (data.students.length === 0) {
        y = checkPageBreak(doc, y, 30);
        doc.rect(
            PDF_LAYOUT.marginLeft,
            y,
            PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight,
            24,
        ).fillColor('#F9FAFB').fill();

        doc.fillColor(PDF_LAYOUT.colors.textLight)
            .font(PDF_LAYOUT.fonts.regular)
            .fontSize(8.5)
            .text('No student attempts or records found for this examination.', PDF_LAYOUT.marginLeft + 12, y + 8);
        y += 24;
    } else {
        data.students.forEach((student, idx) => {
            const namePadding = 6;
            const nameHeight = doc.heightOfString(`${student.lastName}, ${student.firstName}`, {
                width: studentCols[0].width - 12,
            });
            const rowHeight = Math.max(20, nameHeight + namePadding);

            const nextY = checkPageBreak(doc, y, rowHeight);
            if (nextY === PDF_LAYOUT.marginTop) {
                y = drawStudentTableHeader(doc, nextY);
            }

            // Alternating row backgrounds
            if (idx % 2 === 1) {
                doc.rect(
                    PDF_LAYOUT.marginLeft,
                    y,
                    PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight,
                    rowHeight,
                )
                    .fillColor('#F9FAFB')
                    .fill();
            }

            // Bottom border
            doc.moveTo(PDF_LAYOUT.marginLeft, y + rowHeight)
                .lineTo(PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginRight, y + rowHeight)
                .strokeColor(PDF_LAYOUT.colors.border)
                .lineWidth(0.5)
                .stroke();

            const valignOffset = Math.floor((rowHeight - 8) / 2);
            let curX = PDF_LAYOUT.marginLeft;
            doc.fillColor(PDF_LAYOUT.colors.textPrimary);

            // Name / No.
            doc.font(PDF_LAYOUT.fonts.bold);
            doc.text(`${student.lastName}, ${student.firstName}`, curX + 6, y + 3, {
                width: studentCols[0].width - 12,
            });
            doc.font(PDF_LAYOUT.fonts.regular).fillColor(PDF_LAYOUT.colors.textSecondary).fontSize(7);
            doc.text(student.studentNo, curX + 6, y + rowHeight - 8);
            doc.fontSize(8).fillColor(PDF_LAYOUT.colors.textPrimary);
            curX += studentCols[0].width;

            // Section
            doc.text(student.sectionName, curX + 6, y + valignOffset, {
                width: studentCols[1].width - 12,
                lineBreak: false,
            });
            curX += studentCols[1].width;

            // Status
            let statusColor = PDF_LAYOUT.colors.textPrimary;
            if (student.status === 'COMPLETED') statusColor = '#10B981';
            else if (student.status === 'FLAGGED') statusColor = '#EF4444';
            else if (student.status === 'ABSENT') statusColor = '#EC4899';
            else if (student.status === 'IN_PROGRESS') statusColor = '#3B82F6';

            doc.fillColor(statusColor).font(PDF_LAYOUT.fonts.bold);
            doc.text(student.status, curX, y + valignOffset, {
                width: studentCols[2].width,
                align: 'center',
            });
            doc.fillColor(PDF_LAYOUT.colors.textPrimary).font(PDF_LAYOUT.fonts.regular);
            curX += studentCols[2].width;

            // Score
            const scoreText = student.score !== null ? `${student.score}%` : '—';
            if (student.score !== null && student.score < data.passingScore) {
                doc.fillColor('#EF4444').font(PDF_LAYOUT.fonts.bold);
            }
            doc.text(scoreText, curX - 6, y + valignOffset, {
                width: studentCols[3].width,
                align: 'right',
            });
            doc.fillColor(PDF_LAYOUT.colors.textPrimary).font(PDF_LAYOUT.fonts.regular);
            curX += studentCols[3].width;

            // Attempt
            let attemptText = 'Standard';
            if (student.attemptKind === 'makeup') attemptText = 'Makeup';
            else if (student.attemptKind === 'retake') attemptText = 'Retake';
            if (student.activeOverrideType) {
                attemptText += ` (${student.activeOverrideType})`;
            }
            doc.text(attemptText, curX, y + valignOffset, {
                width: studentCols[4].width,
                align: 'center',
            });
            curX += studentCols[4].width;

            // Incidents P/R/C/D
            const incidentDetails = `${student.incidentsPending}/${student.incidentsReviewed}/${student.incidentsConfirmed}/${student.incidentsDismissed}`;
            if (student.incidentsConfirmed > 0) {
                doc.fillColor('#EF4444').font(PDF_LAYOUT.fonts.bold);
            } else if (student.incidentsPending > 0) {
                doc.fillColor('#F59E0B');
            } else {
                doc.fillColor(PDF_LAYOUT.colors.textSecondary);
            }
            doc.text(incidentDetails, curX - 6, y + valignOffset, {
                width: studentCols[5].width,
                align: 'right',
            });

            y += rowHeight;
        });
    }
    doc.restore();

    // 4. Unconditional Page Break before Additional Insights
    doc.addPage();
    y = PDF_LAYOUT.marginTop;

    y = drawSectionHeader(doc, 'SECTION-WISE PERFORMANCE & METRICS', y);

    const sectionCols = [
        { name: 'Section Name', width: 200, align: 'left' },
        { name: 'Total Students', width: 100, align: 'center' },
        { name: 'Average Score', width: 90, align: 'right' },
        { name: 'Pass Rate', width: 97, align: 'right' },
    ] as const;

    // Draw Section Table Header
    doc.save();
    doc.rect(
        PDF_LAYOUT.marginLeft,
        y,
        PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight,
        18,
    )
        .fillColor('#4B5563') // medium gray
        .fill();

    let secX = PDF_LAYOUT.marginLeft;
    doc.fillColor('#FFFFFF').font(PDF_LAYOUT.fonts.bold).fontSize(8);
    sectionCols.forEach((col) => {
        const align = col.align;
        const padding = align === 'left' ? 6 : align === 'right' ? -6 : 0;
        doc.text(col.name, secX + padding, y + 5, {
            width: col.width,
            align,
        });
        secX += col.width;
    });
    doc.restore();
    y += 18;

    // Draw Section Rows
    doc.save();
    doc.font(PDF_LAYOUT.fonts.regular).fontSize(8);
    if (data.sections.length === 0) {
        y = checkPageBreak(doc, y, 20);
        doc.text('No section data available.', PDF_LAYOUT.marginLeft + 6, y + 5);
        y += 20;
    } else {
        data.sections.forEach((sec, idx) => {
            y = checkPageBreak(doc, y, 18);
            if (idx % 2 === 1) {
                doc.rect(
                    PDF_LAYOUT.marginLeft,
                    y,
                    PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight,
                    18,
                ).fillColor('#F9FAFB').fill();
            }

            doc.moveTo(PDF_LAYOUT.marginLeft, y + 18)
                .lineTo(PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginRight, y + 18)
                .strokeColor(PDF_LAYOUT.colors.border)
                .lineWidth(0.5)
                .stroke();

            let curX = PDF_LAYOUT.marginLeft;
            doc.fillColor(PDF_LAYOUT.colors.textPrimary);

            doc.text(sec.sectionName, curX + 6, y + 5, { width: sectionCols[0].width - 12 });
            curX += sectionCols[0].width;

            doc.text(sec.totalStudents.toString(), curX, y + 5, { width: sectionCols[1].width, align: 'center' });
            curX += sectionCols[1].width;

            doc.text(`${sec.averageScore}%`, curX - 6, y + 5, { width: sectionCols[2].width, align: 'right' });
            curX += sectionCols[2].width;

            doc.text(`${sec.passRate}%`, curX - 6, y + 5, { width: sectionCols[3].width, align: 'right' });

            y += 18;
        });
    }
    doc.restore();
    y += 15;

    // 5. Integrity Incidents Breakdown & Action Queue
    y = checkPageBreak(doc, y, 150);
    y = drawSectionHeader(doc, 'INTEGRITY & ACTION REQUIREMENTS', y);

    const halfWidth =
        (PDF_LAYOUT.pageWidth - PDF_LAYOUT.marginLeft - PDF_LAYOUT.marginRight - 20) / 2;

    // Left Side: Incident Breakdown
    let incY = y;
    doc.save();
    doc.font(PDF_LAYOUT.fonts.bold)
        .fontSize(9)
        .fillColor(PDF_LAYOUT.colors.textPrimary)
        .text('Incidents by Ingestion Type', PDF_LAYOUT.marginLeft, incY);

    incY += 15;
    if (data.incidentTypes.length === 0) {
        doc.font(PDF_LAYOUT.fonts.regular)
            .fontSize(8)
            .fillColor(PDF_LAYOUT.colors.textLight)
            .text('No integrity incidents flagged during this examination.', PDF_LAYOUT.marginLeft, incY);
    } else {
        data.incidentTypes.forEach((t) => {
            doc.fillColor(PDF_LAYOUT.colors.textSecondary)
                .font(PDF_LAYOUT.fonts.regular)
                .fontSize(8)
                .text(t.type, PDF_LAYOUT.marginLeft, incY, { width: 120, lineBreak: false });

            doc.text(`${t.count} (${t.percentage}%)`, PDF_LAYOUT.marginLeft + 130, incY, {
                width: 90,
                align: 'right',
            });

            incY += 14;
        });
    }
    doc.restore();

    // Right Side: Action Queue & Instructions
    let actionY = y;
    doc.save();
    doc.font(PDF_LAYOUT.fonts.bold)
        .fontSize(9)
        .fillColor(PDF_LAYOUT.colors.textPrimary)
        .text('Required Interventions', PDF_LAYOUT.marginLeft + halfWidth + 20, actionY);

    actionY += 15;
    doc.rect(PDF_LAYOUT.marginLeft + halfWidth + 20, actionY, halfWidth, 60)
        .fillColor('#FEF2F2') // light red background
        .fill();
    doc.rect(PDF_LAYOUT.marginLeft + halfWidth + 20, actionY, 4, 60)
        .fillColor('#EF4444') // red left border
        .fill();

    doc.fillColor('#991B1B')
        .font(PDF_LAYOUT.fonts.bold)
        .fontSize(16)
        .text(data.actionQueueCount.toString(), PDF_LAYOUT.marginLeft + halfWidth + 35, actionY + 12);

    doc.fillColor('#991B1B')
        .font(PDF_LAYOUT.fonts.regular)
        .fontSize(8.5)
        .text('Students in Action/Review Queue', PDF_LAYOUT.marginLeft + halfWidth + 35, actionY + 34);

    actionY += 75;
    doc.fillColor(PDF_LAYOUT.colors.textSecondary)
        .font(PDF_LAYOUT.fonts.regular)
        .fontSize(7.5)
        .text(
            'Note: The action queue includes all students with unresolved proctoring incidents, ' +
            'absences needing makeup scheduling, or scores failing the passing criteria.',
            PDF_LAYOUT.marginLeft + halfWidth + 20,
            actionY,
            { width: halfWidth, align: 'justify' },
        );
    doc.restore();
}

/**
 * Renders an Examination Results Report PDF document.
 *
 * @param headerConfig - PDF header configurations
 * @param footerConfig - PDF footer configurations
 * @param logoBuffer - PNG Buffer of the institution logo (optional)
 * @param source - Raw report export source data
 * @returns PDF document buffer
 */
export async function renderExamResultsReportPdf(
    headerConfig: HeaderConfig,
    footerConfig: FooterConfig,
    logoBuffer: Buffer | null,
    source: ExamReportExportSource,
): Promise<Buffer> {
    const data = mapSourceToViewModel(source);

    return await renderPdfDocumentBuffer(headerConfig, footerConfig, logoBuffer, (doc) => {
        drawExamResultsReportBody(doc, data);
    });
}
